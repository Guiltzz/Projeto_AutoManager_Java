    private void atualizarTabela(){
        DefaultTableModel modelo = (DefaultTableModel) tabOS.getModel();
        
        modelo.setRowCount(0);
        
        String sql = "SELECT os.id, v.placa, c.nome AS cliente, m.nome AS mecanico, s.descricao AS servico, "
           + "os.data_abertura, os.data_conclusao, os.descricao_problema, "
           + "os.diagnostico, os.status, os.valor_cobrado, os.observacao "
           + "FROM ordem_servico os "
           + "JOIN veiculo v ON v.id = os.veiculo_id "
           + "JOIN servico s ON s.id = os.servico_id "
           + "JOIN cliente c ON c.id = v.cliente_id "
           + "JOIN mecanico m ON m.id = os.mecanico_id "
           + "ORDER BY os.id";
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql);
             ResultSet resultado = stmt.executeQuery() ){
            
            while (resultado.next()){
                modelo.addRow(new Object[] {
                     resultado.getInt("id"),
                     resultado.getString("placa"),
                     resultado.getString("cliente"),
                     resultado.getString("mecanico"),
                     resultado.getString("servico"),
                     resultado.getString("data_abertura"),
                     resultado.getString("data_conclusao"),
                     resultado.getString("descricao_problema"),
                     resultado.getString("diagnostico"),
                     resultado.getString("status"),
                     resultado.getBigDecimal("valor_cobrado"),
                     resultado.getString("observacao")
                });
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(
                        this,
                        "Erro ao atualizar tabela:\n" + erro.getMessage(),
                        "Erro no banco de dados",
                        JOptionPane.ERROR_MESSAGE);
        }
    }
    
