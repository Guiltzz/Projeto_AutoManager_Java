    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        //1. Capturar a linha selecionada
        int linha = tabVeiculo.getSelectedRow();

        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione um Veiculo na tabela para alterar");
            return;
        }

        //2. Pegar o ID da limha selecionada
        // O ID não será alterado.
        int id = Integer.parseInt(tabVeiculo.getValueAt(linha,0).toString());

        //3. Ler os novos valores digitados nos campos especie,nome, idade
        String placa = txtPlaca.getText().trim();
        String marca = txtMarca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String anoText = txtAno.getText().trim();
        String cor = txtCor.getText().trim();
        Boolean ativo = cbAtivo.isSelected();

        //4. Validar se todos os campos estão preenchidos
        if (placa.isEmpty() && marca.isEmpty() && modelo.isEmpty() && cor.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mude algo");
            return;
        }

        int ano;

        try {
            ano = Integer.parseInt(anoText);

            if (ano < 1900) {
                JOptionPane.showMessageDialog(this, "Ano invalido!");

                return;
            }else if (ano >2100){
                JOptionPane.showMessageDialog(this, "Ano invalido!");

                return;
            }
        } catch (NumberFormatException erro) {
            JOptionPane.showMessageDialog(this,"Erro Verifique as informações");
            return;
        }

        // 6. Pedir Confirmação antes de gravar no banco de dados
        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja alterar os dados do veiculo de ID "+id+"?" ,
            "Confirmar Alteração",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        // 7. Alteramos apenas a escpecie, nome e idade
        // O WHERE garante que somente o animal selecionado será atualziado

        String sql = """
        UPDATE veiculo
        SET placa = ?, marca = ?, modelo = ?, ano = ?, cor = ?, ativo = ?
        WHERE id = ?
        """;

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
            //8. Preecher os Parametros(?) na mesma ordem do SQL
            stmt.setString(1,placa);
            stmt.setString(2,marca);
            stmt.setString(3,modelo);
            stmt.setInt(4,ano);
            stmt.setString(5, cor);
            stmt.setBoolean(6, ativo);
            stmt.setInt(7, id);

            //9. Executamos a alteração no Banco de Dados
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Veiculo alterado com sucesso!");
                atualizarTabela();
                txtPlaca.setText("");
                txtMarca.setText("");
                txtModelo.setText("");
                txtAno.setText("");
                txtCor.setText("");
                cbAtivo.setSelected(false);
            } else {
                JOptionPane.showMessageDialog(this, "Veiculo não encontrado");
            }
        } catch (SQLException erro){
            JOptionPane.showConfirmDialog(this, "Erro ao alterar Veiculo: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnPesquisaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisaActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        String tipo_pesquisa = cbPesquisa.getSelectedItem().toString();

        ///////////////////////////////////////////Conferindo as informaçoes///////////////////////////////////////////
        if (pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                this,
                "Digite o id, marca  ou placa.",
                "Pesquisa Vazia",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) tabVeiculo.getModel();

        modelo.setRowCount(0);

        String sql ="";

        ///////////////////////////////////Verificando Pesquisa/////////////////////////////////////////////////////

        if (tipo_pesquisa == "ID") {
            sql = "SELECT * FROM veiculo "
            + "WHERE id = ?";

        }else if (tipo_pesquisa == "ID Cliente") {

            sql = "SELECT * FROM veiculo "
            + "WHERE cliente_id = ?";

        }else if (tipo_pesquisa == "Placa"){

            sql = "SELECT * FROM veiculo "
            + "WHERE placa ILIKE ? ";

        }else if (tipo_pesquisa == "Marca"){
            sql = "SELECT * FROM veiculo "
            + "WHERE marca ILIKE ?";
        }

        /////////////////////////////////// TRY INSERT //////////////////////////////////////////////////////
        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)) {

            if (tipo_pesquisa.equals("ID")) {
                stmt.setInt(1, Integer.parseInt(pesquisa));

            }else if (tipo_pesquisa.equals("ID Cliente")){

                stmt.setInt(1, Integer.parseInt(pesquisa));

            } else {
                stmt.setString(1, "%" + pesquisa + "%");
            }

            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getInt("cliente_id"),
                        resultado.getString("placa"),
                        resultado.getString("marca"),
                        resultado.getString("modelo"),
                        resultado.getString("ano"),
                        resultado.getString("cor"),
                        resultado.getString("observacao"),
                        resultado.getBoolean("ativo")});
            }
        }
        if (modelo.getRowCount() == 0){
            JOptionPane.showMessageDialog(this,
                "Nenhum Veiculo encontrado para: " + pesquisa,
                "Resultado da Pesquisa",
                JOptionPane.INFORMATION_MESSAGE);
        }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                "Erro ao localizar  :\n" + erro.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnPesquisaActionPerformed

