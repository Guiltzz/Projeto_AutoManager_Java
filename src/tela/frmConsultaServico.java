    private void btnPesquisaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisaActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        String tipo_pesquisa = cbPesquisa.getSelectedItem().toString();
        
        
        ///////////////////////////////////////////Conferindo as informaçoes///////////////////////////////////////////
         if (pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                        this,
                        "Digite o ID, Descrição ou Categoria.",
                        "Pesquisa Vazia",
                        JOptionPane.WARNING_MESSAGE);
            return;
        }
         
         DefaultTableModel modelo = (DefaultTableModel) tabServico.getModel();
        
        modelo.setRowCount(0);
        
        
        String sql ="";
        
        
        
        
        ///////////////////////////////////Verificando Pesquisa/////////////////////////////////////////////////////
        
        if (tipo_pesquisa == "ID") {
            sql = "SELECT * FROM servico "
                  + "WHERE id = ?";
        
        
        
        }else if (tipo_pesquisa == "Descrição") {
        
            sql = "SELECT * FROM servico "
                  + "WHERE descricao ILIKE ?";
               
        
        }else if (tipo_pesquisa == "Categoria"){
        
             sql = "SELECT * FROM servico "
                   + "WHERE categoria ILIKE ? ";
        
}
        
        
        
        /////////////////////////////////// TRY INSERT //////////////////////////////////////////////////////
            try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)) {

            if (tipo_pesquisa.equals("ID")) {
        stmt.setInt(1, Integer.parseInt(pesquisa));
        
            } else {
        stmt.setString(1, "%" + pesquisa + "%");
    }
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getString("descricao"),
                        resultado.getString("categoria"),
                        resultado.getInt("valor_base"),
                        resultado.getInt("tempo_estimado_horas"),
                        resultado.getString("observacao"),
                        resultado.getBoolean("ativo")});
                }
            }
            if (modelo.getRowCount() == 0){
             JOptionPane.showMessageDialog(this,
                           "Nenhum Serviço encontrado para: " + pesquisa,
                           "Resultado da Pesquisa",
                           JOptionPane.INFORMATION_MESSAGE);
              }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                    "Erro ao localizar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
        }
        
         
    
               
    
    }//GEN-LAST:event_btnPesquisaActionPerformed

