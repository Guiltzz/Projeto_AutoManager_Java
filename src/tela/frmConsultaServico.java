    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tabServico.getSelectedRow();

        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione um mecanico para excluir!");
            return;
        }

        int id = Integer.parseInt(tabServico.getValueAt(linha,0).toString());

        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja realmente excluir o serviço do ID "+ id + " ?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM servico WHERE id = ?";

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){

            stmt.setInt(1, id);

            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this, "Serviço excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Serviço não encontrado!");
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,"Erro ao excluir Serviço: "+ erro.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        //1. Capturar a linha selecionada
        int linha = tabServico.getSelectedRow();

        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione um serviço na tabela para alterar");
            return;
        }

        //2. Pegar o ID da limha selecionada
        // O ID não será alterado.
        int id = Integer.parseInt(tabServico.getValueAt(linha,0).toString());

        //3. Ler os novos valores digitados nos campos especie,nome, idade
        String descricao = txtDescricao.getText().trim();
        String categoria = txtCategoria.getText().trim();
        String valorText = txtValor.getText().trim();
        String tempoText = txtTempo.getText().trim();
        String observacao = txtObservacao.getText().trim();
        Boolean ativo = cbAtivo.isSelected();

        //4. Validar se todos os campos estão preenchidos
        if (descricao.isEmpty() && categoria.isEmpty()  && observacao.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mude algo");
            return;
        }
        
        int valor;
        int tempo;
         
         try {
             valor = Integer.parseInt(valorText);
             tempo = Integer.parseInt(tempoText);
             
             if (valor <= 0){
                 JOptionPane.showConfirmDialog(this, "Valor invalido");
                 return;
             }
             
             else if (tempo <=0 ){
                 JOptionPane.showConfirmDialog(this, "Tempo invalido");
                 return;
                 
             }
             
         }catch (NumberFormatException erro) {
             JOptionPane.showMessageDialog(this,"Erro Verifique as informações");
             return;
             
         }

        // 6. Pedir Confirmação antes de gravar no banco de dados
        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja alterar os dados do serviço de ID "+id+"?" ,
            "Confirmar Alteração",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        // 7. Alteramos apenas a escpecie, nome e idade
        // O WHERE garante que somente o animal selecionado será atualziado

        String sql = """
        UPDATE servico
        SET descricao = ?, categoria = ?, valor_base = ?,tempo_estimado_horas = ?, observacao = ?, ativo = ?
        WHERE id = ?
        """;

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
            //8. Preecher os Parametros(?) na mesma ordem do SQL
            stmt.setString(1,descricao);
            stmt.setString(2,categoria);
            stmt.setInt(3,valor);
            stmt.setInt(4,tempo);
            stmt.setString(5, observacao);
            stmt.setBoolean(6, ativo);
            stmt.setInt(7, id);

            //9. Executamos a alteração no Banco de Dados
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Serviço alterado com sucesso!");
                atualizarTabela();
                txtDescricao.setText("");
                txtCategoria.setText("");
                txtValor.setText("");
                txtTempo.setText("");
                txtObservacao.setText("");
                cbAtivo.setSelected(false);
            } else {
                JOptionPane.showMessageDialog(this, "Serviço não encontrado");
            }
        } catch (SQLException erro){
            JOptionPane.showConfirmDialog(this, "Erro ao alterar Serviço: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

