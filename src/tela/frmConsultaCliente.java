    private void btnExlcuirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExlcuirActionPerformed
        int linha = tabCliente.getSelectedRow();

        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione um cliente para excluir!");
            return;
        }

        int id = Integer.parseInt(tabCliente.getValueAt(linha,0).toString());

        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja realmente excluir o cliente do ID "+ id + " ?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM cliente WHERE id = ?";

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){

            stmt.setInt(1, id);

            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this, "Cliente excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Cliente não encontrado!");
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,"Erro ao excluir Cliente: "+ erro.getMessage());
        }

    }//GEN-LAST:event_btnExlcuirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        //1. Capturar a linha selecionada
        int linha = tabCliente.getSelectedRow();

        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione um cliente na tabela para alterar");
            return;
        }

        //2. Pegar o ID da limha selecionada
        // O ID não será alterado.
        int id = Integer.parseInt(tabCliente.getValueAt(linha,0).toString());

        //3. Ler os novos valores digitados nos campos especie,nome, idade
        String nome = txtNome.getText().trim();
        String email = txtEmail.getText().trim();
        String telefone = txtTelefone.getText().trim();
        String cpf = txtCpf.getText().trim();
        String endereco = txtEndereco.getText().trim();
        Boolean ativo = cbAtivo.isSelected();

        //4. Validar se todos os campos estão preenchidos
        if (email.isEmpty() && nome.isEmpty() && telefone.isEmpty() && cpf.isEmpty() && endereco.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mude algo");
            return;
        }

        // 6. Pedir Confirmação antes de gravar no banco de dados
        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja alterar os dados do cliente de ID "+id+"?" ,
            "Confirmar Alteração",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        // 7. Alteramos apenas a escpecie, nome e idade
        // O WHERE garante que somente o animal selecionado será atualziado

        String sql = """
        UPDATE cliente
        SET nome = ?, email = ?, telefone = ?,cpf = ?, endereco = ?, ativo = ?
        WHERE id = ?
        """;

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
            //8. Preecher os Parametros(?) na mesma ordem do SQL
            stmt.setString(1,nome);
            stmt.setString(2,email);
            stmt.setString(3,telefone);
            stmt.setString(4, cpf);
            stmt.setString(5, endereco);
            stmt.setBoolean(6, ativo);
            stmt.setInt(7, id);

            //9. Executamos a alteração no Banco de Dados
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Cliente alterado com sucesso!");
                atualizarTabela();
                txtNome.setText("");
                txtEmail.setText("");
                txtTelefone.setText("");
                txtCpf.setText("");
                txtEndereco.setText("");
                cbAtivo.setSelected(false);
            } else {
                JOptionPane.showMessageDialog(this, "Cliente não encontrado");
            }
        } catch (SQLException erro){
            JOptionPane.showConfirmDialog(this, "Erro ao alterar cliente: " + erro.getMessage());
        }

    }//GEN-LAST:event_btnAlterarActionPerformed

