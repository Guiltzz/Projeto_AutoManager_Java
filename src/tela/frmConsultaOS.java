    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        String tipo_pesquisa = cbPesquisa.getSelectedItem().toString();
        
        
        ///////////////////////////////////////////Conferindo as informaçoes///////////////////////////////////////////
         if (pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                        this,
                        "Digite o Número da OS, Placa, Cliente, Mecânico, Status ou Período de Abertura.",
                        "Pesquisa Vazia",
                        JOptionPane.WARNING_MESSAGE);
            return;
        }
         
         DefaultTableModel modelo = (DefaultTableModel) tabOS.getModel();
        
        modelo.setRowCount(0);
        
        
        
    String base = "SELECT os.id, v.placa, c.nome AS cliente, m.nome AS mecanico, s.descricao AS servico, "
                + "os.data_abertura, os.data_conclusao, os.descricao_problema, "
                + "os.diagnostico, os.status, os.valor_cobrado, os.observacao "
                + "FROM ordem_servico os "
                + "JOIN veiculo v ON v.id = os.veiculo_id "
                + "JOIN servico s ON s.id = os.servico_id "
                + "JOIN cliente c ON c.id = v.cliente_id "
                + "JOIN mecanico m ON m.id = os.mecanico_id ";
        
           String sql = "";
        
        ///////////////////////////////////Verificando Pesquisa/////////////////////////////////////////////////////
        
        if (tipo_pesquisa.equals("ID")) {
        sql = base + "WHERE os.id = ? ORDER BY os.id";
        
    } else if (tipo_pesquisa.equals("Placa")) {
        sql = base + "WHERE v.placa ILIKE ? ORDER BY os.id";
        
    } else if (tipo_pesquisa.equals("Cliente")) {
        sql = base + "WHERE c.nome ILIKE ? ORDER BY os.id";
        
    } else if (tipo_pesquisa.equals("Mecânico")) {
        sql = base + "WHERE m.nome ILIKE ? ORDER BY os.id";
        
    } else if (tipo_pesquisa.equals("Status")) {
        sql = base + "WHERE os.status ILIKE ? ORDER BY os.id";
        
    } else if (tipo_pesquisa.equals("Período de Abertura")) {
        sql = base + "WHERE os.data_abertura = ? ORDER BY os.id";
    }
        
        
        
        /////////////////////////////////// TRY INSERT //////////////////////////////////////////////////////
            try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)) {

            if (tipo_pesquisa.equals("ID")) {
            stmt.setInt(1, Integer.parseInt(pesquisa));
            
        } else if (tipo_pesquisa.equals("Período de Abertura")) {
            DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            stmt.setDate(1, java.sql.Date.valueOf(LocalDate.parse(pesquisa, fmt)));
            
        } else {
            stmt.setString(1, "%" + pesquisa + "%");
        }

            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                    resultado.getInt("id"),
                    resultado.getString("placa"),
                    resultado.getString("cliente"),
                    resultado.getString("mecanico"),
                    resultado.getString("servico"),
                    resultado.getString("data_abertura"),
                    resultado.getString("data_conclusao"),
                    resultado.getString("descricao_problema"),
                    resultado.getString("diagnostico"),
                    resultado.getString("status"),
                    resultado.getBigDecimal("valor_cobrado"),
                    resultado.getString("observacao")
                        });
                }
            }
            if (modelo.getRowCount() == 0){
             JOptionPane.showMessageDialog(this,
                           "Nenhum Ordem Serviço encontrado para: " + pesquisa,
                           "Resultado da Pesquisa",
                           JOptionPane.INFORMATION_MESSAGE);
              }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                    "Erro ao localizar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnPesquisarActionPerformed

