    private void btnExlcuirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExlcuirActionPerformed
        int linha = tabOS.getSelectedRow();

        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione uma Ordem serviço para excluir!");
            return;
        }

        int id = Integer.parseInt(tabOS.getValueAt(linha,0).toString());

        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja realmente excluir a Ordem serviço do ID "+ id + " ?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM ordem_servico WHERE id = ?";

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){

            stmt.setInt(1, id);

            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this, "Ordem serviço excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Ordem serviço não encontrado!");
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,"Erro ao excluir Ordem serviço: "+ erro.getMessage());
        }
    }//GEN-LAST:event_btnExlcuirActionPerformed

