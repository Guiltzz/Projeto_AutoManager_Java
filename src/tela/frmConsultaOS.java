        String diagnostico = txtDiagnostico.getText().trim();
        String observacao = txtObservacao.getText().trim();
        String status = cbEstado.getSelectedItem().toString();

        //4. Validar se todos os campos estão preenchidos
        if (diagnostico.isEmpty()  && observacao.isEmpty() && nomeMecanico.isEmpty() && nomeCliente.isEmpty() ) {
            JOptionPane.showMessageDialog(this, "Mude algo");
            return;
        }

        LocalDate conclusao = null;
        BigDecimal  valor;

        
try {

    if (!dataConcText.replaceAll("[^0-9]", "").isEmpty()) {
        conclusao = LocalDate.parse(dataConcText, DateTimeFormatter.ofPattern("dd/MM/yyyy"));
        if (conclusao.getYear() < 1900 || conclusao.getYear() > 2100) {
            JOptionPane.showMessageDialog(this, "Ano invalido!");
            return;
        }
    }

    txtValor.commitEdit();
    valor = new BigDecimal(txtValor.getValue().toString());

    if (valor.compareTo(BigDecimal.ZERO) <= 0) {
        JOptionPane.showMessageDialog(this, "Valor invalido!");
        return;
    }
} catch (DateTimeParseException erro) {
    JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/mm/aaaa.");
    return;
} catch (NumberFormatException | ParseException | NullPointerException erro) {
    JOptionPane.showMessageDialog(this, "Erro Verifique as informações");
    return;
}

        
        /////mecanico/////
        int mecanico_id;
    try (Connection conex = Conexao.conectar();
         PreparedStatement stmt = conex.prepareStatement("SELECT id FROM mecanico WHERE nome ILIKE ?")) {

        stmt.setString(1, nomeMecanico);
        try (ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                mecanico_id = rs.getInt("id");
            } else {
                JOptionPane.showMessageDialog(this, "Mecânico não encontrado! Digite o nome de um mecânico já cadastrado.");
                return;
            }
        }
    } catch (SQLException erro) {
        JOptionPane.showMessageDialog(this, "Erro ao buscar mecânico: " + erro.getMessage());
        return;
    }
    
    
        /////cliente////
        int cliente_id;
        try (Connection conex = Conexao.conectar();
         PreparedStatement stmt = conex.prepareStatement("SELECT id FROM cliente WHERE nome ILIKE ?")) {

        stmt.setString(1, nomeCliente);
        try (ResultSet rs = stmt.executeQuery()) {
            if (rs.next()) {
                cliente_id = rs.getInt("id");
            } else {
                JOptionPane.showMessageDialog(this, "Cliente não encontrado! Digite o nome de um mecânico já cadastrado.");
                return;
            }
        }
    } catch (SQLException erro) {
        JOptionPane.showMessageDialog(this, "Erro ao buscar mecânico: " + erro.getMessage());
        return;
    }
        
        
     if (status.equals("Concluido")) {
    status = "CONCLUIDA";
} else {
    status = "CANCELADA";
}
        
        // 6. Pedir Confirmação antes de gravar no banco de dados
        int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja alterar os dados da Ordem serviço de ID "+id+"?" ,
            "Confirmar Alteração",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        // 7. Alteramos apenas a escpecie, nome e idade
        // O WHERE garante que somente o animal selecionado será atualziado

        String sql = """
        UPDATE ordem_servico
        SET mecanico_id = ?, data_conclusao = ?, diagnostico = ?, status = ?, valor_cobrado = ?, observacao = ?
        WHERE id = ?
        """;

        try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
            
        
            //8. Preecher os Parametros(?) na mesma ordem do SQL
            stmt.setInt(1, mecanico_id);

            if (conclusao != null) {
            stmt.setDate(2, java.sql.Date.valueOf(conclusao));
            } else {
            stmt.setNull(2, java.sql.Types.DATE);
            }

        stmt.setString(3, diagnostico);
        stmt.setString(4, status);
        stmt.setBigDecimal(5, valor);
        stmt.setString(6, observacao);
        stmt.setInt(7, id);

            //9. Executamos a alteração no Banco de Dados
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Ordem de serviço alterado com sucesso!");
                atualizarTabela();
                txtValor.setText("");
                txtNomeCliente.setText("");
                txtNomeMecanico.setText("");
                txtDiagnostico.setText("");
                txtObservacao.setText("");
                cbEstado.setSelectedItem("Aberto");
            } else {
                JOptionPane.showMessageDialog(this, "Ordem serviço não encontrado");
            }
        } catch (SQLException erro){
            JOptionPane.showConfirmDialog(this, "Erro ao alterar ordem serviço: " + erro.getMessage());
        }
